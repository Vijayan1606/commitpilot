import Link from "next/link";
import { listPatches } from "@/server/db/analysis";
import { getRepository, listRepositories } from "@/server/db/repositories";
import { NewPatchForm } from "@/components/patches/NewPatchForm";
import { Card, CardHeader, EmptyState, PageHeader, Tag, formatDate } from "@/components/ui";
import { getConfig } from "@/server/config/env";

export const dynamic = "force-dynamic";

export default async function PatchesPage({
  searchParams,
}: {
  searchParams: Promise<{ repositoryId?: string; findingId?: string }>;
}) {
  const params = await searchParams;
  const repositories = listRepositories();
  const patches = listPatches(params.repositoryId, 50);
  const config = getConfig();

  return (
    <div className="mx-auto max-w-7xl">
      <PageHeader
        eyebrow="Review gate"
        title="Patch proposals"
        description="A proposal is a diff, not a change. Every diff is validated against the repository before you can approve it, and approval is a separate explicit action."
        actions={<span className="chip">apply {config.allowPatchApply ? "enabled" : "disabled"}</span>}
      />

      <div className="grid gap-6 px-5 py-6 sm:px-8 xl:grid-cols-[minmax(0,1.5fr)_minmax(0,1fr)]">
        <div className="space-y-3">
          {patches.length === 0 ? (
            <EmptyState
              title="No patch proposals"
              description="Ask the assistant for a fix, or use the form. The model only receives bounded file excerpts, and every path is checked before the diff is accepted."
            />
          ) : (
            patches.map((patch) => {
              const repository = getRepository(patch.repositoryId);
              return (
                <Card key={patch.id} className="transition-colors hover:border-citron/30">
                  <Link href={`/patches/${patch.id}`} className="block px-4 py-4">
                    <div className="flex flex-wrap items-start justify-between gap-3">
                      <div className="min-w-0">
                        <div className="flex flex-wrap items-center gap-2">
                          <h2 className="truncate text-sm font-semibold">{patch.title}</h2>
                          <Tag
                            tone={
                              patch.status === "applied"
                                ? "ok"
                                : patch.status === "invalid"
                                  ? "danger"
                                  : patch.status === "rejected"
                                    ? "warn"
                                    : "info"
                            }
                          >
                            {patch.status}
                          </Tag>
                        </div>
                        <p className="mt-1 line-clamp-2 max-w-3xl text-xs leading-relaxed text-muted">
                          {patch.rationale}
                        </p>
                        <p className="mt-1 font-mono text-[10px] text-muted">
                          {repository?.name ?? "removed"} · {patch.files.length} file(s) ·{" "}
                          {formatDate(patch.createdAt)}
                        </p>
                      </div>
                      <div className="text-right text-[11px]">
                        <p className={patch.validation.ok ? "text-ok" : "text-danger"}>
                          {patch.validation.ok ? "validated" : "validation failed"}
                        </p>
                        <p className="mt-0.5 text-muted">{patch.files.length} files</p>
                      </div>
                    </div>
                  </Link>
                </Card>
              );
            })
          )}
        </div>

        <div className="space-y-6">
          <Card>
            <CardHeader
              title="Propose a patch"
              description="Generated by the open model, validated by git. Never applied automatically."
            />
            <NewPatchForm
              repositories={repositories.map((repository) => ({
                id: repository.id,
                name: repository.name,
              }))}
              initialRepositoryId={params.repositoryId}
              initialFindingId={params.findingId}
            />
          </Card>
          <Card>
            <CardHeader title="Safety rules" />
            <ul className="space-y-2 px-4 py-4 text-[11px] leading-relaxed text-muted">
              <li>Only tracked, non-excluded files can be touched.</li>
              <li>No new, deleted, renamed, or mode-changed files are accepted.</li>
              <li>The diff must pass <span className="font-mono">git apply --check</span>.</li>
              <li>Every touched file is copied to a backup directory before applying.</li>
              <li>Applying requires a server flag and a per-patch confirmation.</li>
            </ul>
          </Card>
        </div>
      </div>
    </div>
  );
}
